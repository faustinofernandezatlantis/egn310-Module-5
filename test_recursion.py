# ---------------------------------------------------------------
# Helper: checks that a function really is recursive
# (it calls itself and contains no for/while loops)
# ---------------------------------------------------------------
def is_recursive_without_loops(func):
    source = inspect.getsource(func)
    tree = ast.parse(source)
    name = func.__name__
    calls_itself = False
    has_loop = False
    for node in ast.walk(tree):
        if isinstance(node, (ast.For, ast.While)):
            has_loop = True
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name):
            if node.func.id == name:
                calls_itself = True
    return calls_itself and not has_loop


# ---------------------------------------------------------------
# Function 1: factorial
# ---------------------------------------------------------------
def test_factorial_base_case():
    assert factorial(0) == 1


def test_factorial_one():
    assert factorial(1) == 1


def test_factorial_small():
    assert factorial(5) == 120


def test_factorial_larger():
    assert factorial(10) == 3628800


def test_factorial_is_recursive():
    assert is_recursive_without_loops(factorial), \
        "factorial must call itself and must not use loops"



# ---------------------------------------------------------------
# Function 4: power (converted from iterative)
# ---------------------------------------------------------------
def test_power_exponent_zero():
    assert power(7, 0) == 1


def test_power_exponent_one():
    assert power(9, 1) == 9


def test_power_small():
    assert power(2, 5) == 32


def test_power_base_one():
    assert power(1, 50) == 1


def test_power_matches_iterative():
    # The recursive version must agree with the provided iterative one
    for base in range(0, 6):
        for exp in range(0, 8):
            assert power(base, exp) == power_iterative(base, exp), \
                f"power({base}, {exp}) does not match power_iterative"


def test_power_is_recursive():
    assert is_recursive_without_loops(power), \
        "power must call itself and must not use loops"


